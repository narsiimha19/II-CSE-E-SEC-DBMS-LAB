SELECT * FROM ACCOUNT;
SET SERVEROUTPUT ON;

-- Create ACCOUNT table

CREATE TABLE ACCOUNT
(
    ACCOUNT_NO NUMBER(6) PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(30),
    ACCOUNT_TYPE VARCHAR2(20),
    BALANCE NUMBER(10,2)
);

